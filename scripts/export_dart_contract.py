"""Generate the Dart server's copy of the contract from the Python server.

The Python server is the source of the extension protocol schemas, the MCP tool list
and handshake, and the Direct API tool definitions. This script reads them from a
running in-process Python server and writes them as constants to
`packages/mcp-dart/lib/src/generated/contract.g.dart`, so the two servers describe the same
tools with the same words. `--check` fails when the generated file is out of date
(`scripts/validate_static.py` runs it).
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "packages" / "mcp" / "src" / "chrome_bridge_mcp"
OUTPUT = (
    ROOT / "packages" / "mcp-dart" / "lib" / "src" / "generated" / "contract.g.dart"
)

# Protocol versions a client may ask for; the server answers each with the version it
# speaks. The last one is unknown to every server and shows the fallback.
_PROBED_VERSIONS = [
    "2024-11-05",
    "2025-03-26",
    "2025-06-18",
    "2025-11-25",
    "2099-01-01",
]


def _compact(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _raw(name: str, value: str) -> str:
    if "'''" in value:
        raise ValueError(f"{name} contains ''' and cannot be a raw Dart string")
    return f"const {name} = r'''{value}''';\n"


def _read_server() -> dict[str, Any]:
    logging.disable(logging.CRITICAL)
    from starlette.testclient import TestClient

    from chrome_bridge_mcp import Settings, create_app

    headers = {
        "accept": "application/json, text/event-stream",
        "content-type": "application/json",
    }

    def rpc(client: Any, method: str, params: dict[str, Any]) -> Any:
        response = client.post(
            "/mcp",
            headers=headers,
            json={"jsonrpc": "2.0", "id": 1, "method": method, "params": params},
        )
        response.raise_for_status()
        return response.json()["result"]

    with TestClient(create_app(Settings()), base_url="http://127.0.0.1:8765") as client:
        answered: dict[str, str] = {}
        initialize: dict[str, Any] = {}
        for version in _PROBED_VERSIONS:
            result = rpc(
                client,
                "initialize",
                {
                    "protocolVersion": version,
                    "capabilities": {},
                    "clientInfo": {"name": "export", "version": "1"},
                },
            )
            answered[version] = result.pop("protocolVersion")
            initialize = result
        tools = rpc(client, "tools/list", {})["tools"]
        direct = client.get("/api/v1/tools").json()["tools"]
    supported = [version for version, answer in answered.items() if answer == version]
    return {
        "initialize": initialize,
        "supported": supported,
        "fallback": answered[_PROBED_VERSIONS[-1]],
        "tools": tools,
        "direct": direct,
    }


def render() -> str:
    server = _read_server()
    v1 = json.loads(
        (SCHEMA_DIR / "protocol_v1.schema.json").read_text(encoding="utf-8")
    )
    v2 = json.loads(
        (SCHEMA_DIR / "protocol_v2.schema.json").read_text(encoding="utf-8")
    )
    parts = [
        "// Generated by scripts/export_dart_contract.py from the Python server.\n",
        "// Do not edit: run `uv run python scripts/export_dart_contract.py`.\n",
        "// ignore_for_file: lines_longer_than_80_chars\n\n",
        _raw("protocolV1Schema", _compact(v1)),
        _raw("protocolV2Schema", _compact(v2)),
        _raw("mcpInitializeResult", _compact(server["initialize"])),
        _raw("mcpSupportedProtocolVersions", _compact(server["supported"])),
        f"const mcpFallbackProtocolVersion = '{server['fallback']}';\n",
        _raw("mcpTools", _compact(server["tools"])),
        _raw("directTools", _compact(server["direct"])),
    ]
    return "".join(parts)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when out of date")
    args = parser.parse_args()
    content = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.is_file() else ""
        if current != content:
            sys.exit(
                f"{OUTPUT.relative_to(ROOT)} is out of date: "
                "run `uv run python scripts/export_dart_contract.py`"
            )
        print("Dart contract is up to date.")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
